"""Collect per-vehicle metrics from SUMO tripinfo XML into CSV for evaluation."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
import xml.etree.ElementTree as ET

DEFAULT_OUTPUT = Path("evaluation/results")


def _safe_float(value: str | None) -> str:
    if value is None:
        return ""
    return value.strip()


def tripinfo_to_csv(tripinfo_path: Path, output_path: Path) -> Path:
    """Convert SUMO tripinfo XML into a flat CSV with one row per vehicle."""
    tree = ET.parse(tripinfo_path)
    root = tree.getroot()
    rows: list[dict[str, str]] = []

    for vehicle in root.findall("vehicle"):
        row = {key: _safe_float(vehicle.attrib.get(key, "")) for key in vehicle.attrib}
        rows.append(row)

    if not rows:
        raise ValueError(f"No vehicle records found in {tripinfo_path}")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = sorted({field for row in rows for field in row})
    with output_path.open("w", encoding="utf-8", newline="") as csv_file:
        writer = csv.DictWriter(csv_file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    return output_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tripinfo", type=Path, help="Path to tripinfo.xml generated by SUMO")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT / "tripinfo.csv", help="CSV output path")
    args = parser.parse_args()

    try:
        output = tripinfo_to_csv(args.tripinfo, args.output)
    except (ET.ParseError, OSError, ValueError) as error:
        parser.error(str(error))

    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
